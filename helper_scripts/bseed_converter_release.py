#!/usr/bin/env python3
"""Produce and verify the immutable BSEED Zigbee2MQTT converter release manifest.

The GitHub-hosted workflow runs this only after generating and syntax-checking
the converter from device_db.yaml + the maintained Jinja template.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import re

SUPPORTED_Z2M_MAJOR_MINOR = "2.14"
REQUIRED_MARKERS = (
    "bseed_pm_sample_time_ms",
    "bseed_pm_sample_power_w",
    "bseed_pm_telemetry_quarantine",
    "bseedSocketRelayOnOff",
)
REQUIRED_PM_BUILDS = (
    "1.2.5-bseedcli15",
    "1.2.5-bseedcli16",
    "1.2.5-bseedr13",
)


def event_source_sha() -> str:
    event = os.environ.get("GITHUB_EVENT_PATH")
    if event and Path(event).is_file():
        payload = json.loads(Path(event).read_text(encoding="utf-8"))
        sha = ((payload.get("pull_request") or {}).get("head") or {}).get("sha")
        if sha:
            return sha
    return os.environ.get("GITHUB_SHA", "")


def build_manifest(code: bytes, source_sha: str) -> dict:
    if not re.fullmatch(r"[0-9a-f]{40}", source_sha):
        raise ValueError("source commit must be an exact 40-char Git SHA")
    text = code.decode("utf-8")
    if "module.exports" not in text or "const bseedPmElectricityMeter" not in text:
        raise ValueError("not the generated BSEED Zigbee2MQTT converter")
    for marker in REQUIRED_MARKERS:
        if marker not in text:
            raise ValueError(f"missing BSEED capability: {marker}")
    start = text.index("const knownBuilds = new Set([")
    end = text.index("]);", start)
    builds = sorted(set(re.findall(r'"(1\.2\.5-bseed(?:cli|r)\d+)"', text[start:end])))
    missing = sorted(set(REQUIRED_PM_BUILDS) - set(builds))
    if missing:
        raise ValueError(f"unhandled PM release builds: {missing}")
    return {
        "schema": 1,
        "kind": "zigbee2mqtt_external_converter",
        "name": "switch_custom.js",
        "source_repository": "analienx/tuya-zigbee-switch",
        "source_commit": source_sha,
        "sha256": hashlib.sha256(code).hexdigest(),
        "size_bytes": len(code),
        "compatible_zigbee2mqtt_major_minor": SUPPORTED_Z2M_MAJOR_MINOR,
        "capabilities": list(REQUIRED_MARKERS),
        "bseed_known_pm_builds": builds,
        "hardware_acceptance": False,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--converter", required=True, type=Path)
    parser.add_argument("--output", required=True, type=Path)
    parser.add_argument("--source-commit")
    parser.add_argument("--check", action="store_true",
                        help="compare the manifest without modifying it")
    args = parser.parse_args()
    manifest = build_manifest(args.converter.read_bytes(),
                              args.source_commit or event_source_sha())
    if args.check:
        existing = json.loads(args.output.read_text(encoding="utf-8"))
        if existing != manifest:
            raise SystemExit("converter release manifest differs from generated bytes")
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(manifest, indent=2) + "\n",
                               encoding="utf-8")
    print("BSEED_CONVERTER_RELEASE", manifest["sha256"],
          manifest["source_commit"], "checked" if args.check else "created")


if __name__ == "__main__":
    main()
